"""Writes data/photos.js from media/sizes.json + the hand-picked lists below.
Only the best photos are shown. Edit the lists, then run:
    python tools/build_data.py           (check)
    python tools/build_data.py --prune   (also delete unused photos from media/ to keep the site small)"""
import os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sizes = json.load(open(os.path.join(ROOT, "media", "sizes.json")))

def ids(spec):
    """'beit-asaf 9 32 17' -> ['beit-asaf-009', 'beit-asaf-032', 'beit-asaf-017']"""
    out = []
    for group in spec.split(","):
        name, *nums = group.split()
        out += [f"{name}-{int(n):03d}" for n in nums]
    return out

# Strongest first. Keep each to ~12-16 so nothing feels like a dump.
SERVICES = {
    "events": ids("beit-asaf 9 32 17 12 29 10 30 23 20 13 33 14, soldiers 2, transport 13 14 3"),
    "portraits": ids("bw-portraits 6, flash 1, portraits 3, soldiers 1, drone 3, bw-portraits 5, flash 2,"
                     "portraits 4, street 24, bw-portraits 10, flash 3, portraits 1, beit-asaf 15, portraits 2, flash 4"),
    "business": ids("malka 2 13 21 24 7 18 11 26 9 5 15 22"),
    "property": ids("architecture 1, drone 5, architecture 6 16 8, drone 6, architecture 12 4 9, drone 1, architecture 3 5"),
    "personal": ids("street 26 14 9 1 11 15 17 41 42 28 6 33, bw 3 7, transport 4 5"),
}
SELECTED = ids("beit-asaf 32, bw-portraits 6, malka 2, architecture 1, flash 1, drone 3, beit-asaf 17,"
               "portraits 3, malka 21, street 26, soldiers 1, transport 13, drone 5, beit-asaf 9,"
               "bw-portraits 5, malka 24, street 14, architecture 6, flash 2, beit-asaf 29, portraits 4,"
               "malka 13, street 9, architecture 16")
# Photos used only by projects / hero / about
ALSO_USED = ids("beit-asaf 10, drone 2 4, street 25, transport 6 9 12")

primary = {}
for svc in ("business", "events", "property", "portraits", "personal"):
    for p in SERVICES[svc]:
        primary.setdefault(p, svc)
for p in ALSO_USED:
    primary.setdefault(p, "events" if p.startswith(("transport", "beit-asaf")) else "portraits")

used = set(primary) | set(SELECTED)
missing = sorted(p for p in used if p not in sizes)
assert not missing, f"missing photos: {missing}"

out = {
    "sizes": {k: sizes[k] for k in sorted(used)},
    "primary": primary,
    "services": SERVICES,
    "selected": SELECTED,
}
os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
with open(os.path.join(ROOT, "data", "photos.js"), "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/build_data.py - edit the lists there.\nwindow.PHOTOS=" + json.dumps(out, separators=(",", ":")) + ";\n")

unused = sorted(k for k in sizes if k not in used)
print({s: len(v) for s, v in SERVICES.items()}, "selected", len(SELECTED), "total shown", len(used), "unused", len(unused))
if "--prune" in sys.argv:
    for k in unused:
        for sub in ("full", "thumb"):
            p = os.path.join(ROOT, "media", sub, k + ".jpg")
            if os.path.exists(p):
                os.remove(p)
    print("pruned", len(unused))
