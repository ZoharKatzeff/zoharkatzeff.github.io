"""Writes data/photos.js from media/sizes.json + the hand-picked lists below.
Only the best photos are shown. Edit the lists, then run:
    python tools/build_data.py           (check)
    python tools/build_data.py --prune   (also delete unused photos from media/ to keep the site small)"""
import os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sizes = json.load(open(os.path.join(ROOT, "media", "sizes.json")))

def ids(spec):
    """'beit-asaf 9 32 17' -> ['beit-asaf-009', 'beit-asaf-032', 'beit-asaf-017']"""
    out = []
    for group in spec.split(","):
        name, *nums = group.split()
        out += [f"{name}-{int(n):03d}" for n in nums]
    return out

# Strongest first. Keep each to ~12-16 so nothing feels like a dump.
SERVICES = {
    "events": ids("beit-asaf 9 32, party 1, street 24, beit-asaf 17, soldiers 3, party 2, beit-asaf 29, hike 2, beit-asaf 30 23, drone 3, beach 1, beit-asaf 33, soldiers 4 2"),
    "portraits": ids("bw-portraits 6, flash 1, portraits 3, soldiers 1, flash 2, portraits 4,"
                     "portraits 5, flash 3, street 43, beit-asaf 15, hike 1"),
    "commercial": ids("malka 2, fitness 1, malka 13 21, fitness 2, malka 24 7 18 11 26 9 5 15 22"),
    "property": ids("architecture 1, drone 5, architecture 6 16 8, drone 6, architecture 12 4 9, drone 7, architecture 3 5"),
    "vehicles": ids("transport 4 16 13 5 1 14 15 11 9 3 12 6 8"),
    "artistic": ids("bw-portraits 5, bw 1, street 26 14, bw-street 1, street 9 1 11 15 17 41 42 6 33, bw 3 7"),
}
# Home page photo
HOME = ["self-portrait-001"]

used = {p for lst in SERVICES.values() for p in lst} | set(HOME)
missing = sorted(p for p in used if p not in sizes)
assert not missing, f"missing photos: {missing}"
no_file = sorted(p for p in used for sub in ("full", "thumb") if not os.path.exists(os.path.join(ROOT, "media", sub, p + ".jpg")))
assert not no_file, f"photo files missing from media/ (run tools/build_media.py photos): {no_file}"

out = {
    "sizes": {k: sizes[k] for k in sorted(used)},
    "services": SERVICES,
}
os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
with open(os.path.join(ROOT, "data", "photos.js"), "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/build_data.py - edit the lists there.\nwindow.PHOTOS=" + json.dumps(out, separators=(",", ":")) + ";\n")

unused = sorted(k for k in sizes if k not in used)
print({s: len(v) for s, v in SERVICES.items()}, "total shown", len(used), "unused", len(unused))
if "--prune" in sys.argv:
    for k in unused:
        for sub in ("full", "thumb"):
            p = os.path.join(ROOT, "media", sub, k + ".jpg")
            if os.path.exists(p):
                os.remove(p)
    print("pruned", len(unused))
